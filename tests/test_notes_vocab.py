# The 18 Arturia characteristics, docs/arturia-taxonomy.md, written exactly as
# they appear in LibraryEntry.tags. Duplicated here on purpose: if someone edits
# the lexicon's canonical values, this list is the independent witness.
ARTURIA_CHARACTERISTICS = [
    "Acid", "Aggressive", "Ambient", "Bizarre", "Bright", "Complex", "Dark",
    "Digital", "Ensemble", "Funky", "Hard", "Long", "Noise", "Quiet", "Short",
    "Simple", "Soft", "Soundtrack",
]

# The §1.4 key set, exactly. A key added on either side without a schema bump is
# a silent interop break, so the on-disk shape is asserted, not just parsed.
NOTE_KEYS = {"id", "recorded_at", "source", "text", "text_corrected", "locale",
             "session_id", "audio_start", "audio_end", "device_identity",
             "proposals"}
PROPOSAL_KEYS = {"value", "span", "confidence", "accepted"}

META = bytes(9)


def blob7(seed: int) -> bytes:
    out = bytearray()
    x = (seed % 126) + 1
    while len(out) < p.BLOB_SIZE:
        x = (x * 75 + 74) % 127
        out.append(x)
    return bytes(out[:p.BLOB_SIZE])


def note(text: str, *, note_id: str, recorded_at: str, audio_start: float,
         audio_end=None, source: NoteSource = NoteSource.VOICE,
         session: str = "31d0b6c58f9e4a7d8b2c1e0f4a6d8b3c") -> PresetNote:
    """A note with every non-deterministic field pinned, so a test can compare
    whole documents."""
    return PresetNote(id=note_id, recorded_at=recorded_at, source=source,
                      text=text, text_corrected=None, locale="en-US",
                      session_id=session, audio_start=audio_start,
                      audio_end=audio_end, device_identity="hardware",
                      proposals=extract(text))


# ---------------------------------------------------------------- extractor

def test_fixture(cases) -> None:
    """Every shared case, exactly. The fixture is the definition of correct
    (§5.3): a disagreement between the cores is a missing fixture case, never a
    judgement call."""
    failures = []
    for c in cases:
        got = extract(c["transcript"])
        actual = {
            "verdict": got.verdict.value if got.verdict else None,
            "category": got.category.value if got.category else None,
            "tags": list(got.tag_values),
        }
        if actual != c["expected"]:
            failures.append(f"{c['id']}\n    want {c['expected']}\n    got  {actual}"
                            f"\n    why  {c['why']}")
    assert not failures, "extractor disagrees with the shared fixture:\n  " \
        + "\n  ".join(failures)
    print(f"PASS  extractor: {len(cases)}/{len(cases)} shared fixture cases")


def test_fixture_proposal_shape(cases) -> None:
    """Beyond the values the fixture pins: every emitted proposal must come from
    the closed set (§1.6), carry a §2.8 tier confidence, and its span must
    address the VERBATIM transcript — not the normalized form."""
    verdict_slugs = {v.slug for v in Verdict} - {"unrated"}
    category_slugs = {c.slug for c in Category} - {"uncategorized"}
    tiers = {0.9, 0.8, 0.7}
    seen = 0
    for c in cases:
        text = c["transcript"]
        got = extract(text)
        for kind, proposal in (("verdict", got.verdict), ("category", got.category)):
            if proposal is None:
                continue
            pool = verdict_slugs if kind == "verdict" else category_slugs
            assert proposal.value in pool, (c["id"], kind, proposal.value)
        for t in got.tags:
            assert t.value in ARTURIA_CHARACTERISTICS, (c["id"], t.value)
        for proposal in [got.verdict, got.category, *got.tags]:
            if proposal is None:
                continue
            seen += 1
            assert proposal.confidence in tiers, (c["id"], proposal.confidence)
            assert proposal.accepted is False, c["id"]
            span = proposal.span_text(text)
            assert span is not None and span.strip() == span and span, (c["id"], span)
            # the span is a slice of the ORIGINAL text, so it round-trips
            assert text[proposal.span_start:proposal.span_end] == span
    assert seen > 40, seen
    print(f"PASS  proposals: {seen} closed-set values, tier confidences, "
          "verbatim spans")


def test_lexicon_integrity() -> None:
    """The tables themselves: no key longer than 3 tokens (the scan only ever
    tries 3), no key claimed by two lexicons (which would make the §2.4 tie
    order load-bearing in a way no fixture case covers), and canonical values
    drawn only from the three closed sets."""
    for table, name in ((VERDICT_KEYS, "verdict"), (TYPE_KEYS, "type"),
                        (CHARACTERISTIC_KEYS, "characteristic")):
        for value, keys in table.items():
            for key in keys:
                assert key == key.lower().strip(), (name, key)
                assert 1 <= len(key.split(" ")) <= MAX_KEY_TOKENS, (name, key)
    for key in CARRIERS:
        assert 1 <= len(key.split(" ")) <= MAX_KEY_TOKENS, key
        assert key == key.lower().strip(), key
    claimed = {}
    for table, kind in ((VERDICT_KEYS, MatchKind.VERDICT),
                        (TYPE_KEYS, MatchKind.CATEGORY),
                        (CHARACTERISTIC_KEYS, MatchKind.CHARACTERISTIC)):
        for keys in table.values():
            for key in keys:
                assert key not in claimed, f"{key!r} in two lexicons"
                claimed[key] = kind
    assert set(LEXICON) == set(claimed)
    assert set(VERDICT_KEYS) == {v.slug for v in Verdict} - {"unrated"}
    assert set(TYPE_KEYS) == {c.slug for c in Category} - {"uncategorized"}
    assert CHARACTERISTICS == ARTURIA_CHARACTERISTICS
    print(f"PASS  lexicons: {len(LEXICON)} unique keys, {len(CARRIERS)} carriers, "
          "closed canonical sets")


def test_tokenize_spans() -> None:
    """§2.2: trailing punctuation is outside the span, and a contraction's
    pieces share the range of the single original token."""
    toks = tokenize("nice dark pad, bit too noisy, keep")
    assert [t.text for t in toks] == ["nice", "dark", "pad", "bit", "too",
                                      "noisy", "keep"]
    assert (toks[2].start, toks[2].end) == (10, 13)     # 'pad', not 'pad,'
    toks = tokenize("don't keep it")
    assert [t.text for t in toks] == ["do", "not", "keep", "it"]
    assert (toks[0].start, toks[0].end) == (0, 5)
    assert (toks[1].start, toks[1].end) == (0, 5)       # both pieces = "don't"
    # A CURLY apostrophe does NOT expand: the §2.1 contraction table's keys are
    # written with the ASCII apostrophe, so `it’s` falls through to step 4 and
    # joins to `its`. Both cores do exactly this (verified against the Swift
    # tokenizer), which is what parity requires; widening the table to the
    # typographic form would be a two-core change plus a fixture case.
    assert [t.text for t in tokenize("it’s 8 bit")] == ["its", "8", "bit"]
    assert [t.text for t in tokenize("it's 8 bit")] == ["it", "is", "8", "bit"]
    # digits survive normalization (§2.1 step 5): 303, 808, 8 bit
    assert [t.text for t in tokenize("classic 303")] == ["classic", "303"]
    # NFC: a decomposed e-acute is one code point after normalization
    assert [t.text for t in tokenize("éclat")] == ["éclat"]
    print("PASS  tokenize: spans exclude dropped punctuation, contractions share "
          "one range")


def test_locale_gate_and_content_gate() -> None:
    """§2.0 locale gate (advisory layer only) and §2.9 empty-note gate (the
    CALLER's job, deliberately not extract's)."""
    assert extract("dark pad, keep", locale="fr-FR") == NoteProposals.EMPTY
    assert extract("dark pad, keep", locale="en-GB").verdict is not None
    assert extract("dark").tag_values == ("Dark",)      # extraction still fires
    assert not meets_content_gate("dark")               # but it is never stored
    assert not meets_content_gate("303")                # a digit is not alphabetic
    assert alphabetic_token_count("303 8 bit") == 1
    assert meets_content_gate("dark pad")
    print("PASS  locale gate skips only the advisory layer; content gate needs "
          "two alphabetic tokens")


def test_segment_verdict() -> None:
    """§2.7 segment scope: the last utterance's verdict, or any <=4-token
    utterance's, latest wins."""
    long_desc = "keep this preset for the deep bass texture"
    assert extract(long_desc).verdict is None            # positional rule
    assert segment_verdict([long_desc]) is None
    # a bare 'keep' said EARLY in a long segment still counts
    v = segment_verdict(["keep", "and it has a really nice long release on it"])
    assert v is not None and v.value == "keep"
    # the last utterance's verdict wins when it is later
    v = segment_verdict(["keep", "on reflection this one is meh"])
    assert v is not None and v.value == "meh"
    assert segment_verdict([]) is None
    print("PASS  segment verdict: last utterance or any <=4-token one, latest wins")


def test_proposal_helpers() -> None:
    """The core types the app binds to. `unrated`/`uncategorized` are never
    proposed, so an unparseable value must yield None and never a false
    default."""
    got = extract("nice dark pad, bit too noisy, keep")
    assert got.verdict_value is Verdict.KEEP
    assert got.category_value is Category.PAD
    assert got.tag_values == ("Dark", "Noise")
    assert not got.is_empty and NoteProposals.EMPTY.is_empty
    bogus = NoteProposals(verdict=NoteProposal("nonsense", 0, 1, 0.9),
                          category=NoteProposal("nonsense", 0, 1, 0.9))
    assert bogus.verdict_value is None and bogus.category_value is None
    accepted = got.verdict.accepting()
    assert accepted.accepted and not got.verdict.accepted
    assert accepted.value == got.verdict.value and accepted.span_start == got.verdict.span_start
    assert got.verdict.span_text("short") is None       # span off the end
    print("PASS  proposal helpers: closed-set parse, accepting() copies, span "
          "guards")


