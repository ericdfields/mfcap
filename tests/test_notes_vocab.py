"""Voice notes: the shared extractor fixture, the note sidecar, and the two
Library behaviours that touch it (remove GC, dedupe merge).

Contract: docs/voice-notes.md. The extractor half is driven by
tests/fixtures/note_extraction.json — the SAME file the Swift core's
NoteExtractorTests loads — so a disagreement between the cores shows up here as
a failing case rather than as a silent divergence on the iPad.

The sidecar half pins the interop bytes: the exact key set, explicit nulls,
canonical order, the §1.2 schema gate, and one golden document that was
generated by BOTH cores and compared as parsed JSON (identical), so this file
also stands as the recorded evidence of that comparison.

No microphone, no device, no network: the extractor is pure and the sidecar is
a file.
"""
